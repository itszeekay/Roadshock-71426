#!/usr/bin/env python3
"""Build an index of the ASR5601S decompiled functions.

For each decompiled file it resolves the Ghidra DAT_/PTR_ literals against the
image, so the index shows which peripherals a function touches, which strings it
references, and which functions it calls.

    python tools/asr_index.py --image dumps/asr/asr_flash.bin \
        --decomp reverse/asr/decomp --out reverse/asr/app_index.md
"""
import argparse
import pathlib
import re
import struct

BASE = 0x10000000
STR = re.compile(r"PTR_s_([A-Za-z0-9_]+)_([0-9a-f]{8})")
DAT = re.compile(r"\bDAT_([0-9a-f]{8})\b")
FUN = re.compile(r"\bFUN_([0-9a-f]{8})\b")
FUNC = re.compile(r"// FUNC 0x([0-9a-f]{8})\s+(\S+)")

PERIPH = {
    0x40000000: "CLK/RST?",
    0x40001000: "UART1 base",
    0x40002000: "UART2 base",
    0x40015000: "KEYPAD",
    0x40018000: "UART3",
    0x40030000: "GPIO",
    0x40110000: "IOMUX/PINCFG",
    0x40160000: "SYSCFG?",
    0x40200000: "NVIC?",
}


def decode_periph(val):
    for base, name in PERIPH.items():
        if base <= val < base + 0x1000:
            return "%s+0x%03X" % (name, val - base)
    if 0x20000000 <= val < 0x20030000:
        return "RAM"
    return None


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--image", required=True)
    p.add_argument("--decomp", required=True)
    p.add_argument("--out", required=True)
    args = p.parse_args()

    img = pathlib.Path(args.image).read_bytes()

    def lit(addr):
        off = addr - BASE
        if 0 <= off <= len(img) - 4:
            return struct.unpack_from("<I", img, off)[0]
        return None

    rows = []
    for f in sorted(pathlib.Path(args.decomp).glob("*.c")):
        text = f.read_text(encoding="utf-8", errors="replace")
        m = FUNC.search(text)
        if not m:
            continue
        addr = int(m.group(1), 16)
        name = m.group(2)
        periphs = set()
        for dm in DAT.finditer(text):
            v = lit(int(dm.group(1), 16))
            if v:
                d = decode_periph(v)
                if d:
                    periphs.add(d)
        strs = sorted({"%s" % s.replace("_", " ") for s, _ in STR.findall(text)})
        calls = sorted({int(x, 16) for x in FUN.findall(text)} - {addr})
        rows.append((addr, name, periphs, strs, calls))

    with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("# ASR5601S application function index\n\n")
        fh.write("Generated by `tools/asr_index.py` from `reverse/asr/decomp`.\n\n")
        fh.write("| Address | Name | Peripherals | Strings | Calls |\n|---|---|---|---|---|\n")
        for addr, name, periphs, strs, calls in rows:
            ph = ", ".join(sorted(periphs)) or "-"
            st = "<br>".join(s[:60].replace("|", "\\|") for s in strs[:4]) or "-"
            cl = " ".join("`%08X`" % c for c in calls[:6]) or "-"
            if len(calls) > 6:
                cl += " +%d" % (len(calls) - 6)
            fh.write("| `0x%08X` | `%s` | %s | %s | %s |\n" % (addr, name, ph, st, cl))

    print("functions indexed:", len(rows))
    print("wrote", args.out)


if __name__ == "__main__":
    main()
